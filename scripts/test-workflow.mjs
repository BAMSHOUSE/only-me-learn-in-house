import assert from "node:assert/strict";
import {readFile} from "node:fs/promises";
import ts from "typescript";
const code=ts.transpileModule(await readFile("lib/workflow.ts","utf8"),{compilerOptions:{module:ts.ModuleKind.ESNext,target:ts.ScriptTarget.ES2022}}).outputText;
const {deadlineAfterApproval,completion,ready,types,bucket,stepDone}=await import("data:text/javascript;base64,"+Buffer.from(code).toString("base64"));
assert.equal(deadlineAfterApproval("2026-10-26T16:59:00Z"),"2026-11-09");
assert.equal(deadlineAfterApproval("2026-10-26T17:01:00Z"),"2026-11-10","Uses Bangkok date across midnight");
assert.equal(deadlineAfterApproval("2026-12-24T10:00:00Z"),"2027-01-07");
assert.equal(deadlineAfterApproval("2028-02-20T10:00:00Z"),"2028-03-05","Leap year");
const job={audio_received:0,delivered_at:null};
const m=Object.fromEntries(types.map(type=>[type,{type,status:"not_started"}]));
assert.equal(completion(job,Object.values(m)).percent,0);
job.audio_received=1;
m.thai_scenario.status="submitted";
assert(stepDone("thai_scenario",job,m));
assert(!stepDone("customer_approval",job,m));
assert.equal(completion(job,Object.values(m)).count,2);
assert(!ready("english_script",job,m));
m.thai_scenario.status="rejected";
assert(!stepDone("thai_scenario",job,m),"Customer rejection reopens draft");
m.thai_scenario.status="approved";m.english_script.status="approved";
assert(ready("video_assets",job,m)&&ready("vocabulary",job,m),"Parallel branches unlocked after English");
assert(!ready("pdf",job,m));
m.video_assets.status="approved";
assert(ready("listening",job,m)&&ready("imitation",job,m)&&ready("exercise",job,m));
for(const type of types)m[type].status="approved";
m.admin_send.status="not_started";
m.timestamps.status="not_started";
assert(ready("timestamps",job,m));
assert.equal(completion(job,Object.values(m)).count,10);
m.timestamps.status="approved";
assert.deepEqual(completion(job,Object.values(m)),{count:11,percent:91});
assert(ready("admin_send",job,m));
assert.notEqual(bucket(job,Object.values(m)),"delivered");
m.admin_send.status="approved";
assert.deepEqual(completion(job,Object.values(m)),{count:12,percent:100});
assert.equal(bucket(job,[...Object.values(m),{type:"final_qa",status:"rejected"}]),"delivered","Obsolete QA cannot block completion");
assert(!ready("timestamps",job,m));
console.log(JSON.stringify({ok:true,checks:["Bangkok midnight","month/year rollover","leap year","split Thai and customer approval","parallel branches","12-stage progress","Admin Send completion"]}));
